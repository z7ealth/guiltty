// Generates lib/guiltty/unicode/width_table.ex from glibc's wcwidth(3).
//
// Programs (ls, bash's readline, vim) decide how many columns a character
// takes by calling wcwidth(). If the terminal disagrees, every column after
// that character is off. So instead of reading the Unicode tables
// ourselves, we ask the same function the programs ask, once, and bake the
// answer into Elixir.
//
//   make width-table      rebuilds and rewrites the Elixir module

#define _GNU_SOURCE

#include <gnu/libc-version.h>
#include <locale.h>
#include <stdio.h>
#include <wchar.h>

constexpr unsigned max_cp = 0x10FFFF;

// Width as guiltty uses it: -1 (not printable, or unassigned) counts as 1,
// so such a character still takes a cell and shows up.
static int width(unsigned cp) {
    if (cp >= 0xD800 && cp <= 0xDFFF)
        return 1; // surrogates never arrive: UTF-8 decoding rejects them
    int w = wcwidth((wchar_t)cp);
    return w < 0 ? 1 : w;
}

static void ranges(int wanted) {
    unsigned start = 0;
    bool in = false;
    for (unsigned cp = 0; cp <= max_cp + 1; cp++) {
        bool hit = cp <= max_cp && cp >= 0x20 && width(cp) == wanted;
        if (hit && !in) {
            start = cp;
            in = true;
        } else if (!hit && in) {
            printf("    {0x%X, 0x%X},\n", start, cp - 1);
            in = false;
        }
    }
}

int main(void) {
    if (setlocale(LC_CTYPE, "C.UTF-8") == nullptr) {
        fprintf(stderr, "gen_width: no C.UTF-8 locale\n");
        return 1;
    }
    printf("# Generated by c_src/tools/gen_width.c from glibc's wcwidth(3)\n"
           "# (%s). Don't edit: run `make width-table`.\n"
           "defmodule Guiltty.Unicode.WidthTable do\n"
           "  @moduledoc false\n\n"
           "  @doc \"Inclusive codepoint ranges of width 0.\"\n"
           "  def zero do\n    {\n",
           gnu_get_libc_version());
    ranges(0);
    printf("    }\n  end\n\n  @doc \"Inclusive codepoint ranges of width 2.\"\n  def wide do\n    {\n");
    ranges(2);
    printf("    }\n  end\nend\n");
    return 0;
}
