# Writes c_src/text_table.h, the one table c_src/text_nif.c looks
# codepoints up in. Run by `make text-table`; the header is checked in.
#
#   mix run --no-start c_src/tools/gen_text_table.exs OUT.h GraphemeBreakProperty-*.txt
#
# (It writes the file itself: `mix run` may print to stdout first.)
#
# Each codepoint is one of three classes:
#
#   narrow  - grapheme break property "Other", one column (not listed)
#   wide    - grapheme break property "Other", two columns
#   complex - any other grapheme break property (Extend, ZWJ, Prepend,
#             SpacingMark, Hangul jamo, regional indicators, controls)
#
# Widths come from Guiltty.Unicode.WidthTable, the table Elixir uses, so
# C and Elixir can't disagree on one. The break property comes from the
# Unicode Character Database, one file per Unicode version an OTP guiltty
# supports uses (OTP 26 has 15.0, OTP 29 has 17.0). A codepoint is complex
# if it is in any of them: complex text goes to the running OTP's
# String.graphemes/1, which is right whatever its version. (U+11A3A was
# Prepend in 15.0 and is Other since 15.1.)
alias Guiltty.Unicode.WidthTable

[out | paths] = System.argv()
texts = Enum.map(paths, &File.read!/1)

versions =
  for text <- texts do
    [_, version] = Regex.run(~r/^# GraphemeBreakProperty-([\d.]+)\.txt/, text)
    version
  end

# Lines are "0300..036F ; Extend # ..." or "00AD ; Control # ...". The
# ranges of all the files overlap; the merge below joins them.
complex =
  for text <- texts,
      line <- String.split(text, "\n"),
      [range | _] = String.split(line, ";"),
      range =~ ~r/^[0-9A-F]/ do
    case range |> String.trim() |> String.split("..") do
      [lo] -> {String.to_integer(lo, 16), String.to_integer(lo, 16)}
      [lo, hi] -> {String.to_integer(lo, 16), String.to_integer(hi, 16)}
    end
  end

# Guiltty.Unicode.char_width/1 calls everything below U+0300 narrow.
wide =
  for {lo, hi} <- Tuple.to_list(WidthTable.wide()), hi >= 0x300, do: {max(lo, 0x300), hi}

# Complex wins over wide: a wide codepoint that can join others goes to
# Elixir like any other complex one. Ranges are cut where they overlap,
# then neighbours of the same class are merged.
cut_out = fn {lo, hi}, holes ->
  Enum.reduce(holes, [{lo, hi}], fn {a, b}, pieces ->
    Enum.flat_map(pieces, fn {l, h} ->
      cond do
        b < l or a > h -> [{l, h}]
        true -> Enum.filter([{l, a - 1}, {b + 1, h}], fn {x, y} -> x <= y end)
      end
    end)
  end)
end

ranges =
  (Enum.map(complex, &{&1, :complex}) ++
     for(r <- wide, piece <- cut_out.(r, complex), do: {piece, :wide}))
  |> Enum.sort()
  |> Enum.reduce([], fn
    # Touching or overlapping (the same range in several versions).
    {{lo, hi}, class}, [{{plo, phi}, class} | rest] when lo <= phi + 1 ->
      [{{plo, max(hi, phi)}, class} | rest]

    range, acc ->
      [range | acc]
  end)
  |> Enum.reverse()

hex = &("0x" <> String.pad_leading(Integer.to_string(&1, 16), 4, "0"))

header = """
// Generated by c_src/tools/gen_text_table.exs from GraphemeBreakProperty.txt
// of Unicode #{Enum.join(versions, ", ")} and Guiltty.Unicode.WidthTable
// (glibc's wcwidth). Don't edit: run `make text-table`.

#pragma once

#include <stdint.h>

enum cp_class : uint8_t { cp_narrow, cp_wide, cp_complex };

struct cp_range {
    uint32_t lo, hi;
    enum cp_class class;
};

// Sorted, not overlapping. A codepoint in none of them is narrow.
static const struct cp_range cp_ranges[] = {
"""

rows = for {{lo, hi}, class} <- ranges, do: "    {#{hex.(lo)}, #{hex.(hi)}, cp_#{class}},\n"
File.write!(out, [header, rows, "};\n"])
